"""`txncat errors`: error analysis of the best external-test model (E5), written to reports/.

Needs the database only to look up each row's description and direction (predictions/*.csv store ids, labels and
predictions, not text). Outputs: reports/error_analysis.md, reports/metrics/error_analysis.json,
reports/figures/error_types.png.
"""

from __future__ import annotations

import json
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

from txncat.config import REPO_ROOT
from txncat.eval.errors import ERROR_TYPES, TOP_N, TYPE_KEYS, analyze
from txncat.eval.report import FIG_DIR, METRICS_DIR, MODELS, PRED_DIR, load_split

MD_PATH = REPO_ROOT / "reports" / "error_analysis.md"
SPLIT = "external_test"
BEST = "E5"
OTHERS = ["E1", "E2", "E3", "E4"]
POS_PREFIX = r"(?i)^\s*(SQ \*|TST\s?\*)"  # Square and Toast point-of-sale prefixes


def load_text(engine: Any | None = None) -> pd.DataFrame:
    from sqlalchemy import text

    from txncat.db import make_engine

    engine = engine or make_engine()
    with engine.connect() as conn:
        return pd.read_sql(
            text("SELECT id, split, description, direction FROM transactions WHERE split IN ('test', :s) ORDER BY id"),
            conn,
            params={"s": SPLIT},
        )


def other_overuse(texts: pd.DataFrame, pred_dir: Path = PRED_DIR) -> dict[str, Any]:
    """How often E4 vs E5 answer 'Other' for rows whose true class is NOT Other, split by whether the description has
    a Square/Toast POS prefix (one of E5's three 'Other' few-shot examples is 'SQ *MEMPHIS FLORIST')."""
    out: dict[str, Any] = {}
    for split in ("test", SPLIT):
        p = load_split(split, pred_dir)
        desc = pd.DataFrame({"id": p.ids}).merge(texts[["id", "description"]], on="id", how="left")["description"]
        prefixed = desc.fillna("").str.match(POS_PREFIX).to_numpy()
        not_other = p.y != "Other"
        out[split] = {}
        for m in ("E4", "E5"):
            pred = p.cols[m][0]
            out[split][m] = {
                name: {"rows": int(mask.sum()), "share_answered_other": float(np.mean(pred[mask] == "Other"))}
                for name, mask in (("pos_prefix", not_other & prefixed), ("no_prefix", not_other & ~prefixed))
            }
    return out


def build(texts: pd.DataFrame, pred_dir: Path = PRED_DIR) -> tuple[dict[str, Any], pd.DataFrame]:
    from txncat.data.taxonomy import category_names

    p = load_split(SPLIT, pred_dir)
    texts = texts[texts["split"] == SPLIT].drop(columns="split") if "split" in texts else texts
    rows = pd.DataFrame({"id": p.ids, "category": p.y}).merge(texts, on="id", how="left", validate="one_to_one")
    if rows["description"].isna().any():
        raise ValueError("some prediction ids have no description in the database; reload the data")
    preds: dict[str, np.ndarray] = {BEST: p.cols[BEST][0]}
    for m in OTHERS:
        for i, arr in enumerate(p.cols[m]):
            preds[m if len(p.cols[m]) == 1 else f"{m}_seed{i}"] = arr
    result = analyze(rows, preds, BEST, category_names())
    # E3: average the fix rate over its 3 seeds for the summary table
    for fx in result["fixed_by"].values():
        seeds = [v for k, v in fx.items() if k.startswith("E3_seed")]
        if seeds:
            fx["E3"] = float(np.mean(seeds))
    return result, result.pop("sample")


def markdown(res: dict[str, Any], sample: pd.DataFrame, meta: dict[str, Any]) -> str:
    n_err = res["n_errors"]
    L = [
        "# Error analysis (M6)",
        "",
        f"Generated by `{meta['command']}` on {meta['date']} at commit `{meta['commit']}`.",
        "",
        f"Model: **{MODELS[BEST][0]}** (best on the independent external set, M5). It gets {n_err} of "
        f"{res['n_rows']} external rows wrong ({n_err / res['n_rows']:.1%}). Each error is assigned one type by "
        "deterministic rules in `src/txncat/eval/errors.py` (first matching rule wins).",
        "",
        "## Error types, and which model gets those rows right",
        "",
        "| Error type | E5 errors | share | E1 right | E2 right | E3 right (mean of 3 seeds) | E4 right | What it is |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for t in ERROR_TYPES:
        c = res["counts"][t.key]
        fx = res["fixed_by"][t.key]
        cells = [f"{fx[m]:.0%}" if c else "–" for m in OTHERS]
        L.append(f"| {t.title} | {c} | {c / n_err:.0%} | " + " | ".join(cells) + f" | {t.meaning} |")
    L += [
        "",
        '"X right" = share of that type\'s rows (all wrong for E5) that model X classifies correctly.',
        "",
        "**True classes inside each type**",
        "",
    ]
    for t in ERROR_TYPES:
        by = res["by_true_class"][t.key]
        if by:
            L.append(f"- {t.title}: " + ", ".join(f"{c} {n}" for c, n in by.items()))
    ov = res.get("other_overuse")
    if ov:
        L += [
            "",
            "## Few-shot examples push the LLM towards 'Other'",
            "",
            "Share of rows whose true class is NOT Other that the LLM answers 'Other', zero-shot (E4) vs few-shot "
            "(E5), split by whether the description starts with a Square/Toast POS prefix (`SQ *`, `TST*`). One of "
            "E5's three 'Other' examples (from train, fixed seed) is `SQ *MEMPHIS FLORIST`.",
            "",
            "| Split | rows | E4 zero-shot → Other | E5 few-shot → Other |",
            "|---|---|---|---|",
        ]
        for split, d in ov.items():
            for name, label in (("pos_prefix", "POS prefix"), ("no_prefix", "no prefix")):
                L.append(
                    f"| {split}, {label} | {d['E4'][name]['rows']} | {d['E4'][name]['share_answered_other']:.1%} | "
                    f"{d['E5'][name]['share_answered_other']:.1%} |"
                )
        L += [
            "",
            "This is a correlation, not a tested cause: changing the examples and re-measuring would need a fresh "
            "selection rule checked on val (not on these test sets).",
        ]
    L += [
        "",
        f"## {TOP_N} sampled E5 errors",
        "",
        f"A seeded random sample (seed 0) of {TOP_N} errors: the LLM gives no confidence score to rank 'top' errors "
        "by. Descriptions come from the external dataset (DoDataThings v2, MIT licence; see data/README.md).",
        "",
        "| Type | Description | Dir | True | E5 said | E5 raw reply | E2 | E3 s0 |",
        "|---|---|---|---|---|---|---|---|",
    ]
    titles = {t.key: t.title for t in ERROR_TYPES}
    for r in sample.itertuples():
        raw = getattr(r, "raw", "") or ""
        L.append(
            f"| {titles[r.type]} | `{r.description}` | {r.direction} | {r.category} | {r.pred} | {raw} | "
            f"{'✓' if r.E2_right else '✗'} | {'✓' if r.E3_seed0_right else '✗'} |"
        )
    L.append("")
    return "\n".join(L)


def figure(res: dict[str, Any], path: Path) -> Path:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    keys = [k for k in TYPE_KEYS if res["counts"][k]]
    titles = {t.key: t.title for t in ERROR_TYPES}
    mat = np.array([[res["fixed_by"][k][m] for m in OTHERS] for k in keys])
    fig, (ax0, ax1) = plt.subplots(1, 2, figsize=(10, 0.5 * len(keys) + 1.8), width_ratios=[1, 1.4], sharey=True)
    counts = [res["counts"][k] for k in keys]
    ax0.barh(range(len(keys)), counts, color="#2a6fdb")
    for i, c in enumerate(counts):
        ax0.text(c, i, f" {c}", va="center", fontsize=8)
    ax0.set_yticks(range(len(keys)), [titles[k] for k in keys], fontsize=8)
    ax0.invert_yaxis()
    ax0.set_xlabel("E5 errors on external set")
    ax0.spines[["top", "right"]].set_visible(False)
    ax1.imshow(mat, cmap="Greens", vmin=0, vmax=1, aspect="auto")
    for i in range(len(keys)):
        for j in range(len(OTHERS)):
            ax1.text(
                j,
                i,
                f"{mat[i, j]:.0%}",
                ha="center",
                va="center",
                fontsize=8,
                color="white" if mat[i, j] > 0.6 else "black",
            )
    ax1.set_xticks(range(len(OTHERS)), [MODELS[m][0].split(" ", 1)[0] for m in OTHERS], fontsize=8)
    ax1.set_title("share of those rows each other model gets right", fontsize=9)
    fig.suptitle("Where the few-shot LLM (E5) fails, and who fixes it", fontsize=10)
    fig.tight_layout()
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=150)
    plt.close(fig)
    return path


def run() -> int:
    from txncat.models.train_cli import _git_commit

    meta = {
        "command": "txncat errors",
        "date": datetime.now(UTC).isoformat(timespec="seconds"),
        "commit": _git_commit(),
    }
    texts = load_text()
    res, sample = build(texts)
    res["other_overuse"] = other_overuse(texts)
    raw = pd.read_csv(PRED_DIR / MODELS[BEST][1][0], usecols=["id", "split", "raw"], keep_default_na=False)
    sample = sample.merge(raw[raw["split"] == SPLIT][["id", "raw"]], on="id", how="left")
    MD_PATH.write_text(markdown(res, sample, meta), encoding="utf-8")
    out = {**meta, **res, "types": [t.__dict__ for t in ERROR_TYPES], "sample_ids": [int(i) for i in sample["id"]]}
    (METRICS_DIR / "error_analysis.json").write_text(json.dumps(out, indent=2) + "\n", encoding="utf-8")
    fig = figure(res, FIG_DIR / "error_types.png")
    print(MD_PATH.read_text(encoding="utf-8"))
    for path in (MD_PATH, METRICS_DIR / "error_analysis.json", fig):
        print(f"saved {path.relative_to(REPO_ROOT)}")
    return 0
