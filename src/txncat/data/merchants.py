def _fill(pattern: str, rng: random.Random) -> str:
    surname, surname2 = rng.sample(SURNAMES, 2)
    thing, thing2 = rng.sample(THINGS, 2)
    return pattern.format(
        surname=surname,
        surname2=surname2,
        place=rng.choice(PLACES),
        adj=rng.choice(ADJECTIVES),
        thing=thing,
        thing2=thing2,
        food=rng.choice(FOODS),
        eatery=rng.choice(EATERIES),
        cuisine=rng.choice(CUISINES),
        saas1=rng.choice(SAAS1),
        saas2=rng.choice(SAAS2),
        biz=rng.choice(BIZ),
        trade=rng.choice(TRADES),
    )


def build_merchants(seed: int = 42, per_category: int = TARGET_PER_CATEGORY) -> list[Merchant]:
    """Curated chains + generated locals, unique names across all categories, deterministic for `seed`."""
    rng = random.Random(seed)
    used: set[str] = set()
    out: list[Merchant] = []

    def add(name: str, category: str, kind: str) -> bool:
        if name in used:
            return False
        used.add(name)
        out.append(Merchant(name, category, kind))
        return True

    for category, chains in CHAINS.items():
        for name in chains:
            add(name, category, "payer" if category == "Income / Deposits" else "chain")
    for bank in BANKS:  # bank-specific fee descriptors, e.g. "CHASE OVERDRAFT FEE"
        for fee in FEE_TYPES:
            add(f"{bank} {fee}", "Bank Fees & Charges", "fee")
    for fee in FEE_TYPES:
        add(fee, "Bank Fees & Charges", "fee")

    for category, patterns in LOCAL_PATTERNS.items():
        have = sum(m.category == category for m in out)
        attempts = 0
        while have < per_category and attempts < per_category * 200:
            attempts += 1
            if add(_fill(rng.choice(patterns), rng), category, "local"):
                have += 1
    return out


def write_merchants_csv(merchants: list[Merchant], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(["merchant", "category", "kind"])
        for m in sorted(merchants, key=lambda m: (m.category, m.kind, m.name)):
            w.writerow([m.name, m.category, m.kind])


def read_merchants_csv(path: Path) -> list[Merchant]:
    with path.open(newline="", encoding="utf-8") as f:
        return [Merchant(r["merchant"], r["category"], r["kind"]) for r in csv.DictReader(f)]
